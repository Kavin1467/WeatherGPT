window.I18N = {
    currentLang: "en",
    get: function(key) {
        const langPack = I18N_DATA[this.currentLang] || I18N_DATA["en"];
        return langPack[key] || I18N_DATA["en"][key] || key;
    },
    setLang: function(lang) {
        if (I18N_DATA[lang]) {
            this.currentLang = lang;
            this.applyTranslations();
        }
    },
    getSpeechCode: function() {
        return (I18N_DATA[this.currentLang] || I18N_DATA["en"]).speechCode || "en-IN";
    },
    applyTranslations: function() {
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            const text = this.get(key);
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = text;
            } else {
                el.textContent = text;
            }
        });
    }
};
